function stepStatus(step: PipelineStep): string {
  return { ran: "Ran", skipped: "Skipped", cached: "Cached", failed: "Failed" }[step.status];
}

const GLOSSARY: [string, string][] = [
  ["Evidenced", "Supported by external sources, cited by number and listed in Appendix B."],
  ["Stated", EVIDENCE_LABELS.submission.blurb],
  ["Inferred", EVIDENCE_LABELS["rubric-inference"].blurb],
  ["Band", "The two rubric anchor levels a metric score sits between, e.g. 60–80. Anchors describe what a 20, 40, 60, 80 and 100 look like for that metric."],
  ["Confidence", "How clearly the underlying claim was expressed in the submission — not whether it is true."],
  ["Re-scored", "An automated check flagged the metric as more than 15 points outside its expected band, and it was scored a second time."],
  ["Weighted sum", "The overall score: each metric score multiplied by its weight, added together, computed in code rather than by a model."],
];

function Appendix({ input }: { input: ReportPdfInput }) {
  const { data, weights } = input;
  const trace = data.trace ?? [];
  const sources: EnrichmentSource[] = data.sources ?? [];
  const preset = identifyPreset(weights);
  const [a, b, c, d] = SECTIONS.slice(4);

  return (
    <Page size="A4" style={s.page} bookmark="Appendices">
      <Chrome business={input.business} id={input.id} />
      <SectionTitle n={a.n} title={a.title} />
      <Text style={s.pMuted}>
        How this score was produced. Every step of the fixed six-step pipeline
        is recorded with what it did and which model ran it. The final number
        is arithmetic, not a model&apos;s judgment.
      </Text>
      {trace.length === 0 ? (
        <Text style={s.p}>
          This report was scored before step-by-step tracing was introduced,
          so its pipeline record was not captured. Its score is unchanged and
          remains attributable to the prompt version in Appendix C.
        </Text>
      ) : (
        trace.map((step) => (
          <View key={step.step} style={s.step} wrap={false}>
            <Text style={s.stepNum}>{String(step.step).padStart(2, "0")}</Text>
            <View style={s.stepBody}>
              <Text style={s.stepName}>{step.name}</Text>
              <Text style={s.body}>{step.detail}</Text>
              <Text style={s.stepMeta}>
                {stepStatus(step)}
                {step.model ? ` · ${step.model}` : ""} · {(step.durationMs / 1000).toFixed(1)}s
              </Text>
            </View>
          </View>
        ))
      )}
      <Text style={s.h2}>Weighting</Text>
      <Text style={s.p}>
        {preset ? `${preset.name} — ${preset.source}.` : "Custom weights."}{" "}
        {METRIC_ORDER.map((id) => `${METRIC_LABELS[id]} ${weights[id]}%`).join(" · ")}.
      </Text>

      <View style={{ marginTop: 10 }}>
        <SectionTitle n={b.n} title={b.title} />
      </View>
      {sources.length === 0 ? (
        <Text style={s.p}>
          No external sources were retrieved for this report. Scores rest on
          the submission itself, which is why evidence-dependent metrics are
          marked Stated rather than Evidenced.
        </Text>
      ) : (
        sources.map((src) => (
          <View key={src.id} style={s.source} wrap={false}>
            <Text style={s.body}>
              <Text style={s.sourceRef}>[S{src.id}] </Text>
              {src.title}
            </Text>
            <Link src={src.url} style={s.sourceUrl}>
              {src.url}
            </Link>
          </View>
        ))
      )}

      <View style={{ marginTop: 10 }} wrap={false}>
        <SectionTitle n={c.n} title={c.title} />
        {[
          ["Report ID", input.id],
          ["Generated", formatDate(input.date)],
          ["Prompt version", input.promptVersion],
          ["Scoring model", `${input.scorerModel} · temperature 0.1`],
          ["Final score", "Weighted sum computed in code, not by a model"],
          ["Result", input.fromCache ? "Reused from a near-identical earlier submission" : "Scored fresh for this submission"],
        ].map(([k, v]) => (
          <View key={k} style={s.kv}>
            <Text style={s.k}>{k}</Text>
            <Text style={s.v}>{v}</Text>
          </View>
        ))}
      </View>

      <View style={{ marginTop: 14 }} wrap={false}>
        <SectionTitle n={d.n} title={d.title} />
        {GLOSSARY.map(([term, def]) => (
          <View key={term} style={s.gloss}>
            <Text style={s.glossTerm}>{term}</Text>
            <Text style={s.glossDef}>{def}</Text>
          </View>
        ))}
        <Text style={s.disclaimer}>{DISCLAIMER}</Text>
      </View>
    </Page>
  );
}

