function EvidenceBadge({ basis }: { basis?: keyof typeof BASIS_INK }) {
  if (!basis) return null;
  const color = BASIS_INK[basis];
  return (
    <Text style={[s.badge, { color, borderColor: color }]}>
      {EVIDENCE_LABELS[basis].label}
    </Text>
  );
}

// 0–100 scale with the grade bands from GRADE_THRESHOLDS and a marker at
// the score. Drawn with plain boxes so it renders identically everywhere.
function ScoreScale({ score }: { score: number }) {
  const bands = (Object.entries(GRADE_THRESHOLDS) as [Grade, number][])
    .sort((a, b) => a[1] - b[1])
    .map(([grade, start], i, all) => ({
      grade,
      start,
      end: all[i + 1]?.[1] ?? 100,
    }));
  const left = Math.max(0, Math.min(100, score));
  return (
    <View style={s.scale}>
      <View style={s.scaleTrack}>
        {bands.map((b) => (
          <View
            key={b.grade}
            style={[
              s.scaleSeg,
              { width: `${b.end - b.start}%`, backgroundColor: GRADE_INK[b.grade], opacity: 0.22 },
            ]}
          />
        ))}
        <View style={[s.scaleMarker, { left: `${left}%` }]} />
      </View>
      <View style={s.scaleLabels}>
        {bands.map((b) => (
          <Text key={b.grade} style={[s.scaleLabel, { left: `${b.start}%` }]}>
            {b.grade}
          </Text>
        ))}
        <Text style={[s.scaleLabel, { right: 0 }]}>100</Text>
      </View>
    </View>
  );
}

